export type UnitType = "camera" | "apartament" | "garsoniera" | "casuta";

export type Amenity =
  | "wifi"
  | "parking"
  | "breakfast"
  | "kitchen"
  | "fireplace"
  | "pets"
  | "ac"
  | "view"
  | "sea"
  | "pool";

export type Unit = {
  id: string;
  name: string;
  type: UnitType;
  location: string;
  pricePerNight: number; // bani
  rating: number;
  maxGuests: number;
  bedrooms: number;
  beds: number;
  bathrooms: number;
  area: number; // m²
  amenities: Amenity[];
  description: string;
  photos: string[];
  highlights: Amenity[]; // max. 2 facilități-cheie, afișate ca iconițe pe card
  lat: number; // coordonate (aproximative, date de test) – pentru hartă
  lng: number;
  offer?: { percent: number; label: "winter" | "lastMinute" }; // reducere (date de test)
};

// Prețul pe noapte după reducere, rotunjit la leu întreg (în bani)
export function nightly(unit: Unit) {
  if (!unit.offer) return unit.pricePerNight;
  return Math.round((unit.pricePerNight * (100 - unit.offer.percent)) / 100 / 100) * 100;
}

